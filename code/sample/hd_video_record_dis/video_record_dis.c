static HD_RESULT set_proc_cfg(HD_CTRL_ID ctrl, HD_PATH_ID *p_video_proc_ctrl, HD_VIDEOPROC_PIPE pipe, HD_DIM* p_max_dim)
{
	HD_RESULT ret = HD_OK;
	HD_VIDEOPROC_DEV_CONFIG video_cfg_param = {0};
	HD_VIDEOPROC_CTRL video_ctrl_param = {0};
	HD_PATH_ID video_proc_ctrl = 0;

	ret = hd_videoproc_open(0, ctrl, &video_proc_ctrl); //open this for device control
	if (ret != HD_OK)
		return ret;

	if (p_max_dim != NULL ) {
		video_cfg_param.pipe = pipe;

		if (pipe == VPRC_IPP_PIPE) {
			video_cfg_param.isp_id = ISP_ID_0;  // need to isp mapping
		} else if (pipe == HD_VIDEOPROC_PIPE_VPE){ //HD_VIDEOPROC_PIPE_VPE
			video_cfg_param.isp_id = ISP_EFFECT_ID;
		} else { // HD_VIDEOPROC_PIPE_SCALE
		    video_cfg_param.isp_id = ISP_ID_1;  // need to isp mapping
		}

		video_cfg_param.ctrl_max.func = 0;
		if (g_3dnr == 1 && pipe == PIPE_3DNR) {
			video_cfg_param.ctrl_max.func |= HD_VIDEOPROC_FUNC_3DNR | HD_VIDEOPROC_FUNC_3DNR_STA;
		}
		video_cfg_param.in_max.func = 0;
		video_cfg_param.in_max.dim.w = p_max_dim->w;
		video_cfg_param.in_max.dim.h = p_max_dim->h;
		video_cfg_param.in_max.pxlfmt = (pipe == HD_VIDEOPROC_PIPE_VPE) ? g_vpe_in_fmt : CAP_OUT_FMT;
        if (pipe == HD_VIDEOPROC_PIPE_SCALE) {
            video_cfg_param.in_max.pxlfmt = HD_VIDEO_PXLFMT_YUV420;
        }
		video_cfg_param.in_max.frc = HD_VIDEO_FRC_RATIO(1,1);
		ret = hd_videoproc_set(video_proc_ctrl, HD_VIDEOPROC_PARAM_DEV_CONFIG, &video_cfg_param);
		if (ret != HD_OK) {
			return HD_ERR_NG;
		}
	}
	{
		HD_VIDEOPROC_FUNC_CONFIG video_path_param = {0};

		video_path_param.in_func = 0;
		if (g_capbind == 1 && pipe == HD_VIDEOPROC_PIPE_RAWALL) {
			video_path_param.in_func |= HD_VIDEOPROC_INFUNC_DIRECT; //direct NOTE: enable direct
		} else {
		    if(g_capbind ==1) {
		        printf(" pipe %x not support direct !!!\r\n",pipe);
		    }
		}
		ret = hd_videoproc_set(video_proc_ctrl, HD_VIDEOPROC_PARAM_FUNC_CONFIG, &video_path_param);
		//printf("set_proc_param PATH_CONFIG=0x%X\r\n", ret);
	}
	video_ctrl_param.func = 0;
	if (g_3dnr == 1 && pipe == PIPE_3DNR) {
		video_ctrl_param.func |= HD_VIDEOPROC_FUNC_3DNR | HD_VIDEOPROC_FUNC_3DNR_STA;
		//use current path as reference path (if venc.dim == raw.dim)
		video_ctrl_param.ref_path_3dnr = HD_VIDEOPROC_0_OUT_0;
	}
	ret = hd_videoproc_set(video_proc_ctrl, HD_VIDEOPROC_PARAM_CTRL, &video_ctrl_param);
	if (ret != HD_OK) {
		return HD_ERR_NG;
	}

    if(pipe == HD_VIDEOPROC_PIPE_VPE)
    {
		UINT32 in_depth = 3;
        printf("set %x inq 3 \r\n",ctrl);
		ret =vendor_videoproc_set(video_proc_ctrl, VENDOR_VIDEOPROC_PARAM_IN_DEPTH, &in_depth);
	}
	*p_video_proc_ctrl = video_proc_ctrl;

	return ret;
}

