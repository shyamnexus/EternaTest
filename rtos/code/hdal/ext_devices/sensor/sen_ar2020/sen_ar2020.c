static ER sen_write_reg_ar2020(CTL_SEN_ID id, CTL_SEN_CMD *cmd)
{
	struct i2c_msg msgs;
	unsigned char buf[4];
	int i;

	if (!i2c_valid[id]) {
		return E_NOSPT;
	}

	if (1 == cmd->data_len) {
		buf[0]     = (cmd->addr >> 8) & 0xFF;
		buf[1]     = cmd->addr & 0xFF;
		buf[2]     = cmd->data[0] & 0xFF;
		msgs.len   = 3;
	} else {
		buf[0]     = (cmd->addr >> 8) & 0xFF;
		buf[1]     = cmd->addr & 0xFF;
		buf[2]     = cmd->data[0] & 0xFF;
		buf[3]     = cmd->data[1] & 0xFF;
		msgs.len   = 4;
	}
	msgs.addr  = sen_i2c[id].addr;
	msgs.flags = 0;
	msgs.buf   = buf;

	if ((!is_fastboot[id]) || (fastboot_i2c_id[id] != sen_i2c[id].id) || (fastboot_i2c_addr[id] != sen_i2c[id].addr)) {
		i = 0;
		while(1){
			if (sen_i2c_transfer(id, &msgs, 1) == 0)
				break;
			i++;
			if (i == 5)
				return E_SYS;
		}
	} else {
		#if defined(__KERNEL__)
		isp_builtin_set_transfer_i2c(id, &msgs, 1);
		#endif
	}

	return E_OK;
}

static ER sen_read_reg_ar2020(CTL_SEN_ID id, CTL_SEN_CMD *cmd)
{
	struct i2c_msg  msgs[2];
	unsigned char   tmp[2], tmp2[2];
	int i;

	if (!i2c_valid[id]) {
		return E_NOSPT;
	}

	tmp[0]        = (cmd->addr >> 8) & 0xFF;
	tmp[1]        = cmd->addr & 0xFF;
	msgs[0].addr  = sen_i2c[id].addr;
	msgs[0].flags = 0;
	msgs[0].len   = 2;
	msgs[0].buf   = tmp;

	tmp2[0]       = 0;
	tmp2[1]       = 0;
	msgs[1].addr  = sen_i2c[id].addr;
	msgs[1].flags = 1;
	msgs[1].len   = 2;
	msgs[1].buf   = tmp2;

	if ((!is_fastboot[id]) || (fastboot_i2c_id[id] != sen_i2c[id].id) || (fastboot_i2c_addr[id] != sen_i2c[id].addr)) {
		i = 0;
		while(1){
			if (sen_i2c_transfer(id, msgs, 2) == 0)
				break;
			i++;
			if (i == 5)
				return E_SYS;
		}
	} else {
		#if defined(__KERNEL__)
		isp_builtin_set_transfer_i2c(id, msgs, 2);
		#endif
	}

	cmd->data[0] =(tmp2[0] << 8); //(tmp2[0] << 8) | tmp2[1];
	cmd->data[1] = tmp2[1];
	return E_OK;
}

